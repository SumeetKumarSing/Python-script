# maths operators in python

a = 20
b = 10
print(a + b)  # addition
print(a - b)  # subtraction
print(a * b)  # multiplication
print(a / b)  # division
print(a ** b)  # exponentiation
print(7 // 2)  # floor division
print(a % b)  # modulus
